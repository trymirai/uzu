@dataclass(frozen=True)
class Parameter:
    name: str
    # The Metal value type, or None for a type parameter.
    value_type: str | None
    variants: tuple[str, ...]


@dataclass(frozen=True)
class Argument:
    name: str
    # The Metal element type with qualifiers, pointers and array extents removed.
    element: str
    # "buffer", "constant_buffer", "constant_array", "value" or "dispatch".
    storage: str
    writable: bool = False
    array_length: str | None = None
    optional: str | None = None
    specialize: bool = False
    # The annotation name and its expressions, for a dispatch argument.
    dispatch: tuple[str, tuple[str, ...]] | None = None


@dataclass(frozen=True)
class Kernel:
    name: str
    parameters: tuple[Parameter, ...]
    constraints: tuple[str, ...]
    arguments: tuple[Argument, ...]


def annotations(node):
    def strings(child):
        if child["kind"] == "StringLiteral":
            yield json.loads(child["value"])
        for nested in child.get("inner", []):
            yield from strings(nested)

    return [list(strings(child)) for child in node.get("inner", []) if child["kind"] == "AnnotateAttr"]


def constants(path):
    """Macros and constants visible from `path`, for expanding them in annotation expressions."""
    defines = {}
    visited = set()

    def read(header):
        header = header.resolve()
        if header in visited:
            return
        visited.add(header)
        text = header.read_text(encoding="utf-8")
        for include in re.findall(r'^\s*#include "([^"\n]+)"', text, re.M):
            dependency = header.parent / include
            if not dependency.exists():
                dependency = METAL / "generated" / include
            if dependency.exists():
                read(dependency)
        defines.update(re.findall(r"^\s*#define[ \t]+(\w+)[ \t]+([^\n]+)", text, re.M))
        defines.update(
            re.findall(r"(?:static constant constexpr|UZU_CONST)\s+\w+\s+(\w+)\s*=\s*([^;]+);", text)
        )

    read(path)
    return defines


def reported_type(node_type, desugar=True):
    """The type clang reports. Metal 4.1 also names the address space of the declaration itself, the thread's."""
    reported = node_type.get("desugaredQualType", node_type["qualType"]) if desugar else node_type["qualType"]
    words = (w[:-6] if w.endswith(("*thread", "&thread")) else w for w in reported.split())
    return " ".join(w for w in words if w != "thread")


def parse(path, cache):
    """The public kernels declared in a Metal source."""
    source = path.read_bytes()
    result = subprocess.run(
        [
            "xcrun",
            "-sdk",
            "macosx",
            "metal",
            "-x",
            "metal",
            "-std=metal4.1",
            "-mmacosx-version-min=27.0",
            f"-fmodules-cache-path={cache}",
            "-I",
            str(METAL / "generated"),
            "-DDSL_ANALYZE",
            str(path),
            "-fsyntax-only",
            "-Xclang",
            "-ast-dump=json",
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    defines = constants(path)

    def expression(value):
        for _ in range(len(defines) + 1):
            expanded = re.sub(r"\b\w+\b", lambda m: defines.get(m[0], m[0]), value)
            if expanded == value:
                return re.sub(r"\b(\d+)[uU]\b", r"\1", value)
            value = expanded
        raise ValueError(f"recursive macro in {value}")

    def argument(node, derived):
        name = node["name"]
        metal_type = reported_type(node["type"])
        qualifiers = metal_type.split()
        if "threadgroup" in qualifiers or name in derived:
            # Scratch storage and derived values belong to the implementation, not the public API.
            return None
        attributes = annotations(node)
        attribute = attributes[0] if attributes else []
        if attribute and attribute[0] in DISPATCH_ANNOTATIONS:
            annotation = attribute[0].removeprefix("dsl.").capitalize()
            # A stub cannot size its dispatch by what only the Metal kernel derives.
            sizes = tuple("1" if derived & set(re.findall(r"\w+", v)) else expression(v) for v in attribute[1:])
            return Argument(name, "uint", "dispatch", dispatch=(annotation, sizes))
        element = re.sub(r"\b(const|device|constant|threadgroup|coherent)\b|metal::|[&*()]|\[[^]]*\]", "", metal_type)
        element = " ".join(element.split())
        begin, end = node["range"]["begin"], node["range"]["end"]
        begin, end = begin.get("spellingLoc", begin), end.get("spellingLoc", end)
        declaration = source[begin["offset"] : end["offset"] + end["tokLen"]].decode("utf-8")
        array = re.search(r"\[([^]]+)\]", declaration)
        storage, writable, array_length = "value", False, None
        if "device" in qualifiers:
            storage, writable = "buffer", "const" not in qualifiers
        elif "constant" in qualifiers and "*" in metal_type:
            storage = "constant_array" if array else "constant_buffer"
            array_length = expression(array[1]) if array else None
        optional, specialize = None, False
        if attribute:
            if attribute[0] == "dsl.optional":
                optional = expression(attribute[1])
            elif attribute[0] == "dsl.specialize":
                specialize = True
            elif attribute[0] == "dsl.specialize_if":
                optional, specialize = expression(attribute[1]), True
            # A lazy specialization is an ordinary value argument to the other backends.
            elif attribute[0] != "dsl.lazyspecialize":
                raise ValueError(f"unsupported annotation {attribute}")
        return Argument(name, element, storage, writable, array_length, optional, specialize)

    kernels = []
    for node in json.loads(result.stdout)["inner"]:
        template = []
        if node["kind"] == "FunctionTemplateDecl":
            template = [n for n in node["inner"] if n["kind"] in ("TemplateTypeParmDecl", "NonTypeTemplateParmDecl")]
            node = next(n for n in node["inner"] if n["kind"] == "FunctionDecl")
        if node["kind"] != "FunctionDecl":
            continue
        attributes = annotations(node)
        if ["dsl.public"] not in attributes or ["dsl.kernel"] not in attributes:
            continue
        automatic = {a[1] for a in attributes if a[0] == "dsl.autovariants"}
        template = [parameter for parameter in template if parameter["name"] not in automatic]
        derived = automatic | {
            n["name"]
            for n in node["inner"]
            if n["kind"] == "ParmVarDecl" and any(a[0] == "dsl.autospecialize" for a in annotations(n))
        }
        variants = {a[1]: a[2] for a in attributes if a[0] == "dsl.variants"}
        parameters = []
        for parameter in template:
            name = parameter["name"]
            if name not in variants:
                raise ValueError(f"{node['name']}: missing VARIANTS for {name}")
            is_type = parameter["kind"] == "TemplateTypeParmDecl"
            parameters.append(
                Parameter(
                    name,
                    None if is_type else reported_type(parameter["type"], desugar=False),
                    tuple(v.strip() for v in variants[name].split(",")),
                )
            )
        kernels.append(
            Kernel(
                node["name"],
                tuple(parameters),
                tuple(expression(a[1]) for a in attributes if a[0] == "dsl.constraint"),
                tuple(
                    parsed
                    for n in node["inner"]
                    if n["kind"] == "ParmVarDecl" and (parsed := argument(n, derived)) is not None
                ),
            )
        )
    return kernels


class Types:
    """Maps Metal types to one backend's spelling and records the generated GPU types it meets."""

    def __init__(self, names, vectors):
        self.names = names
        self.vectors = vectors
        self.gpu_types = set()

    def __call__(self, metal_type, generics=()):
        if metal_type in generics:
            return metal_type
        if match := VECTOR.fullmatch(metal_type):
            return self.vectors(self(match[1]), match[2])
        if metal_type.startswith("uzu::"):
            _, module, name = metal_type.split("::")
            self.gpu_types.add((module, name))
            return name
        if metal_type not in self.names:
            raise ValueError(f"unsupported Metal type {metal_type!r}")
        return self.names[metal_type]

    def constraint(self, expression):
        """A constraint with the type names it compares variants against respelled for the backend."""
        return re.sub(r'"(\w+)"', lambda m: f'"{self.names.get(m[1], m[1])}"', expression)


def quoted(*values):
    return ", ".join(json.dumps(value) for value in values)


def slang_file(body, modules):
    return "\n".join([MARKER, "import definitions;", *sorted(f"import generated.{m};" for m in modules), "", body, ""])


def emit_slang(kernels):
    types = Types(SLANG_TYPES, lambda element, width: f"vector<{element}, {width}>")
    stubs = []
    for kernel in kernels:
        generic_names = {p.name for p in kernel.parameters}
        generics, lines, arguments = [], [], []
        for parameter in kernel.parameters:
            is_type = parameter.value_type is None
            generics.append(parameter.name if is_type else f"let {parameter.name}: {types(parameter.value_type)}")
            values = [types(v) for v in parameter.variants] if is_type else parameter.variants
            lines.append(f"[[Variants({quoted(parameter.name, ', '.join(values))})]]")
        for argument in kernel.arguments:
            if argument.dispatch:
                annotation, values = argument.dispatch
                arguments.append(f"  [[{annotation}({quoted(*values)})]] uint32_t {argument.name},")
                continue
            element = types(argument.element, generic_names)
            if argument.storage == "buffer":
                ty = f"{'RWStructuredBuffer' if argument.writable else 'StructuredBuffer'}<{element}>"
            elif argument.storage == "constant_array":
                ty = f"{element}[{argument.array_length}]"
            elif argument.storage == "constant_buffer":
                ty = f"[[Constant]] StructuredBuffer<{element}>"
            else:
                ty = element
            prefix = "[[Specialize]] " if argument.specialize else ""
            if argument.optional is not None:
                prefix += f"[[Optional({quoted(argument.optional)})]] "
            arguments.append(f"  {prefix}{ty} {argument.name},")
        lines.extend(f"[[Constraint({quoted(types.constraint(c))})]]" for c in kernel.constraints)
        generic = f"<{', '.join(generics)}>" if generics else ""
        lines.extend([f"[[Public]] [[Kernel]] func {kernel.name}{generic}(", *arguments, ") {", "  // TODO", "}"])
        stubs.append("\n".join(lines))
    return slang_file("\n\n".join(stubs), {module for module, _ in types.gpu_types})


def emit_vulkan(kernels):
    types = Types(VULKAN_TYPES, lambda element, width: element)
    stubs = []
    for kernel in kernels:
        generic_names = {p.name for p in kernel.parameters if p.value_type is None}
        generics, lines, preconditions, specialized_values = [], [], [], []
        for parameter in kernel.parameters:
            if parameter.value_type is None:
                if not set(parameter.variants) <= STORAGE_FLOATS:
                    raise ValueError(f"{kernel.name}: {parameter.name} has variants that are not storage floats")
                generics.append(f"{parameter.name}: IStorageFloat")
                values = ", ".join(types(v) for v in parameter.variants)
                lines.append(f"[[Variants({quoted(parameter.name, values)})]]")
            else:
                if generic_names - {g.split(":")[0] for g in generics}:
                    raise ValueError(f"{kernel.name}: value parameter {parameter.name} precedes a type parameter")
                # Vulkan kernels take value parameters as leading specialized arguments.
                allowed = " || ".join(f"{parameter.name} == {v}" for v in parameter.variants)
                preconditions.append(f"[[Precondition({quoted('new', allowed)})]]")
                specialized_values.append(f"  [[Specialize]] {types(parameter.value_type)} {parameter.name},")
        arguments = []
        for argument in kernel.arguments:
            if argument.dispatch:
                annotation, values = argument.dispatch
                arguments.append(f"  [[{annotation}({quoted(*values)})]] uint {argument.name},")
                continue
            if argument.element == THREAD_CONTEXT:
                continue
            if argument.storage == "constant_array":
                raise ValueError(f"{kernel.name}: constant array {argument.name} has no Vulkan stub form")
            element = types(argument.element, generic_names)
            if argument.storage == "buffer":
                ty = f"Ptr<{element}, Access.{'ReadWrite' if argument.writable else 'Read'}>"
            elif argument.storage == "constant_buffer":
                ty = f"[[Constant]] Ptr<{element}, Access.Read>"
            else:
                ty = element
            prefix = "[[Specialize]] " if argument.specialize else ""
            if argument.optional is not None:
                prefix += f"[[Optional({quoted(argument.optional)})]] "
            if argument.specialize and specialized_values:
                arguments.extend(specialized_values)
                specialized_values = []
            arguments.append(f"  {prefix}{ty} {argument.name},")
        arguments.extend(specialized_values)
        constraints = []
        value_names = {p.name for p in kernel.parameters if p.value_type is not None}
        for constraint in kernel.constraints:
            if not value_names & set(re.findall(r"\w+", constraint)):
                constraints.append(f"[[Constraint({quoted(types.constraint(constraint))})]]")
            elif '"' not in constraint:
                # Value parameters are specialized arguments here, which only a precondition can restrict.
                preconditions.append(f"[[Precondition({quoted('new', constraint)})]]")
            else:
                raise ValueError(f"{kernel.name}: constraint {constraint!r} mixes value and type parameters")
        lines.append("[[Kernel]] [[Public]]")
        lines.extend(preconditions)
        lines.extend(constraints)
        generic = f"<{', '.join(generics)}>" if generics else ""
        lines.extend([f"func {kernel.name}{generic}(", *arguments, ") {", "  // TODO", "}"])
        stubs.append("\n".join(lines))
    return slang_file("\n\n".join(stubs), {module for module, _ in types.gpu_types})


def snake_case(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()


def emit_cpu(kernels):
    types = Types(CPU_TYPES, lambda element, width: element)
    functions = []
    has_type_parameters = False
    for kernel in kernels:
        generic_names = {p.name for p in kernel.parameters if p.value_type is None}
        has_type_parameters |= bool(generic_names)
        generics, lines, arguments = [], [f"#[kernel({kernel.name})]"], []
        for parameter in kernel.parameters:
            if parameter.value_type is None:
                generics.append(f"{parameter.name}: DataTypeRepr + Float")
                values = [types(v) for v in parameter.variants]
            else:
                generics.append(f"const {parameter.name}: {types(parameter.value_type)}")
                values = parameter.variants
            lines.append(f"#[variants({', '.join((parameter.name, *values))})]")
        lines.extend(f"#[constraint({types.constraint(c)})]" for c in kernel.constraints)
        for argument in kernel.arguments:
            if argument.dispatch or argument.element == THREAD_CONTEXT:
                # The CPU kernel covers the whole dispatch itself.
                continue
            element = types(argument.element, generic_names)
            if argument.storage == "buffer":
                ty = f"*{'mut' if argument.writable else 'const'} {element}"
            elif argument.storage == "constant_array":
                ty = f"&[{element}; {argument.array_length}]"
            elif argument.storage == "constant_buffer":
                ty = f"&[{element}]"
            else:
                ty = element
            prefix = "#[specialize] " if argument.specialize else ""
            if argument.optional is not None:
                prefix += f"#[optional({argument.optional})] "
                ty = f"Option<{ty}>"
            arguments.append(f"{prefix}{argument.name}: {ty},")
        generic = f"<{', '.join(generics)}>" if generics else ""
        lines.extend(
            [
                # Every argument is unused until the stub is implemented.
                "#[expect(unused_variables)]",
                f"pub fn {snake_case(kernel.name)}{generic}(",
                *arguments,
                ") {",
                "    todo!()",
                "}",
            ]
        )
        functions.append("\n".join(lines))
    body = "\n\n".join(functions)
    half_types = sorted(name for name in ("bf16", "f16") if re.search(rf"\b{name}\b", body))
    imports = [
        *([f"use half::{{{', '.join(half_types)}}};"] if half_types else []),
        *(["use num_traits::Float;"] if has_type_parameters else []),
        "use uzu_engine_macros::kernel;",
        *(f"use crate::backends::common::gpu_types::{m}::{n};" for m, n in sorted(types.gpu_types)),
        *(["use crate::data_type::DataTypeRepr;"] if has_type_parameters else []),
    ]
    return rustfmt("\n".join([MARKER, *imports, "", body, ""]))


def rustfmt(source):
    result = subprocess.run(
        ["rustfmt", "--config-path", str(ROOT), "--emit", "stdout"],
        input=source,
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout


def declare_module(parent, name, visibility):
    """Adds `mod name;` to the module file of `parent`, keeping its module declarations sorted."""
    module_file = parent / "mod.rs"
    lines = module_file.read_text(encoding="utf-8").splitlines() if module_file.exists() else []
    declaration = re.compile(r"(?:pub(?:\([^)]*\))? )?mod (\w+);")
    declared = [(i, m[1]) for i, line in enumerate(lines) if (m := declaration.fullmatch(line))]
    if name in (module for _, module in declared):
        return
    following = [i for i, module in declared if module > name]
    position = following[0] if following else (declared[-1][0] + 1 if declared else len(lines))
    lines.insert(position, f"{visibility}mod {name};")
    module_file.write_text("\n".join(lines) + "\n", encoding="utf-8")


def declare_cpu_modules(directory, path):
    """Makes the Rust module tree reach a new kernel file."""
    relative = path.relative_to(directory).with_suffix("")
    for depth, name in enumerate(relative.parts):
        declare_module(directory.joinpath(*relative.parts[:depth]), name, "" if depth == 0 else "pub ")


@dataclass(frozen=True)
class Backend:
    name: str
    suffix: str
    emit: object
    declare: object = None

    @property
    def directory(self):
        return BACKENDS / self.name / "kernel"

    def provided_by_hand(self):
        """Kernels whose trait this backend's Rust sources already assign."""
        return {
            name
            for source in self.directory.rglob("*.rs")
            for name in re.findall(r"\btype (\w+)Kernel\s*=", source.read_text(encoding="utf-8"))
        }


TARGETS = (
    Backend("slang", ".slang", emit_slang),
    Backend("vulkan", ".slang", emit_vulkan),
    Backend("cpu", ".rs", emit_cpu, declare_cpu_modules),
)


def main():
    provided = {backend.name: backend.provided_by_hand() for backend in TARGETS}
    generated = {backend.name: {} for backend in TARGETS}
    skipped = {backend.name: 0 for backend in TARGETS}
    with tempfile.TemporaryDirectory(prefix="uzu-kernel-autogen-") as cache:
        for path in sorted(METAL.rglob("*.metal")):
            if not re.search(r"\bPUBLIC\b", path.read_text(encoding="utf-8")):
                continue
            destinations = {}
            for backend in TARGETS:
                destination = backend.directory / path.relative_to(METAL).with_suffix(backend.suffix)
                if destination.exists() and not destination.read_text(encoding="utf-8").startswith(MARKER):
                    skipped[backend.name] += 1
                else:
                    destinations[backend] = destination
            if not destinations:
                continue
            try:
                kernels = parse(path, cache)
            except subprocess.CalledProcessError as error:
                sys.exit(f"{path}: Metal analysis failed:\n{error.stderr}")
            except (OSError, ValueError) as error:
                sys.exit(f"{path}: {error}")
            for backend, destination in destinations.items():
                missing = [kernel for kernel in kernels if kernel.name not in provided[backend.name]]
                if not missing:
                    continue
                try:
                    generated[backend.name][destination] = backend.emit(missing)
                except subprocess.CalledProcessError as error:
                    sys.exit(f"{path}: cannot format the {backend.name} stub:\n{error.stderr}")
                except ValueError as error:
                    sys.exit(f"{path}: no {backend.name} stub: {error}")
    for backend in TARGETS:
        for path, content in generated[backend.name].items():
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                path.write_text(content, encoding="utf-8")
            if backend.declare:
                backend.declare(backend.directory, path)
        files = generated[backend.name]
        count = sum(len(re.findall(r"\[\[Kernel\]\]|#\[kernel\(", content)) for content in files.values())
        print(
            f"{backend.name}: generated {count} public kernel stubs in {len(files)} files; "
            f"skipped {skipped[backend.name]} existing files."
        )


if __name__ == "__main__":
    main()
