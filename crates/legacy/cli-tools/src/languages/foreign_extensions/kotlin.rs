use std::{collections::BTreeSet, fs, path::Path};

use anyhow::{Context, Result};
use heck::AsLowerCamelCase;
use walkdir::WalkDir;

use super::{
    callback_factory::CallbackFactory,
    factory::Factory,
    foreign_extensions::{ForeignExtensions, foreign_type},
    stream_bridge::StreamBridge,
};

/// Writes `Extensions.kt` beside `main_crate`'s UniFFI bindings in `generated_sources_path`. The bindings declare one
/// package per crate, so the extensions live in the main crate's package and import the others.
pub fn generate_kotlin_extensions(
    crates_path: &Path,
    generated_sources_path: &Path,
    main_crate: &str,
) -> Result<()> {
    let mut main_source_path = None;
    let mut packages = BTreeSet::new();
    for entry in WalkDir::new(generated_sources_path) {
        let path = entry?.into_path();
        if path.extension().and_then(|extension| extension.to_str()) != Some("kt") {
            continue;
        }
        let source = fs::read_to_string(&path)?;
        let package = source
            .lines()
            .find_map(|line| line.strip_prefix("package "))
            .with_context(|| format!("{} declares no package", path.display()))?;
        if path.file_stem().and_then(|stem| stem.to_str()) == Some(main_crate) {
            main_source_path = Some((path.clone(), package.trim().to_string()));
        }
        packages.insert(package.trim().to_string());
    }
    let (main_source_path, main_package) =
        main_source_path.with_context(|| format!("No {main_crate}.kt in {}", generated_sources_path.display()))?;
    packages.remove(&main_package);

    let extensions = ForeignExtensions::collect(crates_path)?;
    let directory = main_source_path.parent().context("Generated bindings have no directory")?;
    fs::write(directory.join("Extensions.kt"), render_extensions_file(&extensions, &main_package, &packages)?)?;
    Ok(())
}

fn kotlin_type(
    ty: &syn::Type,
    self_type_name: &str,
) -> Option<String> {
    foreign_type(
        ty,
        self_type_name,
        |name| {
            Some(match name {
                "String" => "String",
                "bool" => "Boolean",
                "i8" => "Byte",
                "i16" => "Short",
                "i32" => "Int",
                "i64" => "Long",
                "u8" => "UByte",
                "u16" => "UShort",
                "u32" => "UInt",
                "u64" => "ULong",
                "f32" => "Float",
                "f64" => "Double",
                _ => return None,
            })
        },
        |inner| format!("List<{inner}>"),
    )
}

fn render_extensions_file(
    extensions: &ForeignExtensions,
    package: &str,
    imported_packages: &BTreeSet<String>,
) -> Result<String> {
    let mut output = format!("// Auto-generated by cli-tools — do not edit.\n\npackage {package}\n\n");
    for imported_package in imported_packages {
        output.push_str(&format!("import {imported_package}.*\n"));
    }
    output.push_str("import kotlinx.coroutines.flow.Flow\n");
    output.push_str("import kotlinx.coroutines.flow.flow\n");
    output.push_str("import kotlinx.coroutines.flow.onCompletion\n\n");
    for (name, ty) in &extensions.aliases {
        if let Some(kotlin_type) = kotlin_type(ty, "") {
            output.push_str(&format!("typealias {name} = {kotlin_type}\n\n"));
        }
    }
    for factory in &extensions.factories {
        if let Some(rendered) = render_factory(factory) {
            output.push_str(&rendered);
        }
    }
    for callback_factory in &extensions.callback_factories {
        output.push_str(&render_callback_factory(callback_factory)?);
    }
    for stream_bridge in &extensions.stream_bridges {
        if let Some(rendered) = render_stream_bridge(stream_bridge) {
            output.push_str(&rendered);
        }
    }
    Ok(format!("{}\n", output.trim_end()))
}

fn render_factory(factory: &Factory) -> Option<String> {
    let type_name = &factory.type_name;
    let method = AsLowerCamelCase(&factory.method_name);
    let parameters = factory
        .arguments
        .iter()
        .map(|argument| {
            Some(format!("{}: {}", AsLowerCamelCase(&argument.name), kotlin_type(&argument.ty, type_name)?))
        })
        .collect::<Option<Vec<_>>>()?
        .join(", ");
    let arguments = factory
        .arguments
        .iter()
        .map(|argument| AsLowerCamelCase(&argument.name).to_string())
        .collect::<Vec<_>>()
        .join(", ");
    let modifier = if factory.is_async {
        "suspend "
    } else {
        ""
    };
    let optional = if factory.optional {
        "?"
    } else {
        ""
    };
    Some(format!(
        "{modifier}fun {type_name}.Companion.{method}({parameters}): {type_name}{optional} = {}({arguments})\n\n",
        factory.free_function_name(),
    ))
}

fn render_callback_factory(factory: &CallbackFactory) -> Result<String> {
    let type_name = &factory.type_name;
    let method = AsLowerCamelCase(&factory.method_name);
    let types = factory
        .callback_arg_types
        .iter()
        .map(|ty| {
            kotlin_type(ty, type_name).with_context(|| format!("No Kotlin type for a {type_name}.{method} callback"))
        })
        .collect::<Result<Vec<_>>>()?;
    let parameters =
        types.iter().enumerate().map(|(index, ty)| format!("arg{index}: {ty}")).collect::<Vec<_>>().join(", ");
    let arguments = (0..types.len()).map(|index| format!("arg{index}")).collect::<Vec<_>>().join(", ");
    Ok(format!(
        "fun {type_name}.Companion.{method}(closure: ({}) -> Unit): {type_name} =\n    \
         {type_name}.{method}(object : {type_name}Handler {{\n        \
         override fun onEvent({parameters}) = closure({arguments})\n    }})\n\n",
        types.join(", "),
    ))
}

fn render_stream_bridge(bridge: &StreamBridge) -> Option<String> {
    let type_name = &bridge.type_name;
    let item_type = kotlin_type(&bridge.item_type, type_name)?;
    let next = AsLowerCamelCase(&bridge.next_method_name);
    let cancel = match &bridge.cancel_getter_name {
        Some(getter) => format!(".onCompletion {{ {}().cancel() }}", AsLowerCamelCase(getter)),
        None => String::new(),
    };
    Some(format!(
        "fun {type_name}.asFlow(): Flow<{item_type}> =\n    flow {{\n        while (true) {{\n            \
         emit({next}() ?: break)\n        }}\n    }}{cancel}\n\n",
    ))
}
