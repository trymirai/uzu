use std::{fs, path::PathBuf};

use anyhow::Result;
use heck::AsLowerCamelCase;

use super::{
    callback_factory::CallbackFactory,
    factory::Factory,
    foreign_extensions::{ForeignExtensions, foreign_type},
    stream_bridge::StreamBridge,
};

pub fn generate_swift_extensions(
    crates_path: PathBuf,
    destination_path: PathBuf,
) -> Result<()> {
    let extensions = ForeignExtensions::collect(&crates_path)?;
    fs::write(&destination_path, render_extensions_file(&extensions))?;
    Ok(())
}

fn swift_type(
    ty: &syn::Type,
    self_type_name: &str,
) -> Option<String> {
    foreign_type(
        ty,
        self_type_name,
        |name| {
            Some(match name {
                "String" => "String",
                "bool" => "Bool",
                "i8" => "Int8",
                "i16" => "Int16",
                "i32" => "Int32",
                "i64" => "Int64",
                "u8" => "UInt8",
                "u16" => "UInt16",
                "u32" => "UInt32",
                "u64" => "UInt64",
                "f32" => "Float",
                "f64" => "Double",
                _ => return None,
            })
        },
        |inner| format!("{inner}?"),
        |inner| format!("[{inner}]"),
    )
}

fn render_extensions_file(extensions: &ForeignExtensions) -> String {
    let mut output = String::new();
    output.push_str("// Auto-generated by cli-tools — do not edit.\n\n");
    for (name, ty) in &extensions.aliases {
        if let Some(swift_type) = swift_type(ty, "") {
            output.push_str(&format!("public typealias {name} = {swift_type}\n\n"));
        }
    }
    for factory in &extensions.factories {
        if let Some(rendered) = render_factory(factory) {
            output.push_str(&rendered);
            output.push('\n');
        }
    }
    for callback_factory in &extensions.callback_factories {
        output.push_str(&render_callback_factory(callback_factory));
        output.push('\n');
    }
    for stream_bridge in &extensions.stream_bridges {
        if let Some(rendered) = render_stream_bridge(stream_bridge) {
            output.push_str(&rendered);
            output.push('\n');
        }
    }
    output
}

fn render_stream_bridge(bridge: &StreamBridge) -> Option<String> {
    let swift_next = AsLowerCamelCase(&bridge.next_method_name).to_string();
    let type_name = &bridge.type_name;
    let item_type = swift_type(&bridge.item_type, type_name)?;
    let (capture, cancel_hook) = match &bridge.cancel_getter_name {
        Some(getter) => {
            let swift_getter = AsLowerCamelCase(getter).to_string();
            ("[weak self] ", format!("\n                self?.{swift_getter}().cancel()"))
        },
        None => ("", String::new()),
    };
    Some(format!(
        r#"extension {type_name} {{
    public func iterator() -> AsyncThrowingStream<{item_type}, Swift.Error> {{
        AsyncThrowingStream<{item_type}, Swift.Error> {{ continuation in
            let task = Task {{
                while !Task.isCancelled {{
                    let item = await self.{swift_next}()
                    guard let item else {{
                        continuation.finish()
                        break
                    }}
                    continuation.yield(item)
                }}
            }}
            continuation.onTermination = {{ {capture}_ in
                task.cancel(){cancel_hook}
            }}
        }}
    }}
}}
"#,
    ))
}

fn render_callback_factory(factory: &CallbackFactory) -> String {
    let type_name = &factory.type_name;
    let swift_method = AsLowerCamelCase(&factory.method_name).to_string();
    let handler_protocol = format!("{}Handler", type_name);
    let wrapper_class = format!("{}HandlerClosureWrapper", type_name);
    let callback_arg_types: Vec<String> = factory
        .callback_arg_types
        .iter()
        .map(|ty| swift_type(ty, type_name).unwrap_or_else(|| "Any".to_string()))
        .collect();

    let closure_args_signature = callback_arg_types
        .iter()
        .enumerate()
        .map(|(index, ty)| {
            let label = format!("arg{index}");
            format!("{label}: {ty}")
        })
        .collect::<Vec<_>>()
        .join(", ");

    let closure_args_forward_positional =
        callback_arg_types.iter().enumerate().map(|(index, _)| format!("arg{index}")).collect::<Vec<_>>().join(", ");

    let closure_type_signature = format!("({}) -> Void", callback_arg_types.join(", "),);

    format!(
        r#"extension {type_name} {{
    public typealias Closure = @Sendable {closure_type_signature}

    private final class {wrapper_class}: Sendable, {handler_protocol} {{
        private let closure: Closure

        init(closure: @escaping Closure) {{
            self.closure = closure
        }}

        func onEvent({closure_args_signature}) {{
            closure({closure_args_forward_positional})
        }}
    }}

    public static func {swift_method}(closure: @escaping Closure) -> {type_name} {{
        {type_name}.{swift_method}(handler: {wrapper_class}(closure: closure))
    }}
}}
"#,
        closure_type_signature = closure_type_signature,
        wrapper_class = wrapper_class,
        handler_protocol = handler_protocol,
        closure_args_signature = closure_args_signature,
        closure_args_forward_positional = closure_args_forward_positional,
        type_name = type_name,
        swift_method = swift_method,
    )
}

fn render_factory(factory: &Factory) -> Option<String> {
    let swift_method = AsLowerCamelCase(&factory.method_name).to_string();
    let free_function = factory.free_function_name();

    let args_signature = factory
        .arguments
        .iter()
        .map(|arg| {
            let ty = swift_type(&arg.ty, &factory.type_name)?;
            Some(format!("{label}: {ty}", label = AsLowerCamelCase(&arg.name)))
        })
        .collect::<Option<Vec<_>>>()?
        .join(", ");

    let args_forward = factory
        .arguments
        .iter()
        .map(|arg| {
            let label = AsLowerCamelCase(&arg.name).to_string();
            format!("{label}: {label}")
        })
        .collect::<Vec<_>>()
        .join(", ");

    let mut return_type = factory.type_name.clone();
    if factory.optional {
        return_type.push('?');
    }

    let mut modifiers = String::new();
    if factory.is_async {
        modifiers.push_str("async ");
    }
    if factory.throws {
        modifiers.push_str("throws ");
    }

    let mut invocation = String::new();
    if factory.throws {
        invocation.push_str("try ");
    }
    if factory.is_async {
        invocation.push_str("await ");
    }
    invocation.push_str(&format!("{free_function}({args_forward})"));

    Some(format!(
        "extension {type_name} {{\n    public static func {method}({args}) {modifiers}-> {ret} {{\n        {invocation}\n    }}\n}}\n",
        type_name = factory.type_name,
        method = swift_method,
        args = args_signature,
        modifiers = modifiers,
        ret = return_type,
        invocation = invocation,
    ))
}
