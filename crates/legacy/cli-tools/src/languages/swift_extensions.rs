use std::{fs, path::Path};

use anyhow::Result;
use heck::AsLowerCamelCase;

use crate::languages::foreign_extensions::{CallbackFactory, Factory, ForeignExtensions, ForeignType, Stream};

pub fn generate_swift_extensions(
    crates_path: &Path,
    destination_path: &Path,
) -> Result<()> {
    let extensions = ForeignExtensions::collect(crates_path)?;
    let mut output = String::from("// Auto-generated by cli-tools — do not edit.\n");
    for (name, aliased) in &extensions.aliases {
        output.push_str(&format!("\npublic typealias {name} = {}\n", swift_type(aliased)));
    }
    for (type_name, exported) in &extensions.types {
        let members = exported
            .factories
            .iter()
            .map(|factory| render_factory(type_name, factory))
            .chain(exported.callback_factories.iter().map(|factory| render_callback_factory(type_name, factory)))
            .chain(exported.stream.iter().map(render_stream))
            .collect::<Vec<_>>()
            .join("\n");
        output.push_str(&format!("\nextension {type_name} {{\n{members}}}\n"));
    }
    fs::write(destination_path, output)?;
    Ok(())
}

fn swift_type(foreign_type: &ForeignType) -> String {
    match foreign_type {
        ForeignType::Optional(inner) => format!("{}?", swift_type(inner)),
        ForeignType::List(inner) => format!("[{}]", swift_type(inner)),
        ForeignType::Named(name) => match name.as_str() {
            "String" => "String",
            "bool" => "Bool",
            "i8" => "Int8",
            "i16" => "Int16",
            "i32" => "Int32",
            "i64" => "Int64",
            "u8" => "UInt8",
            "u16" => "UInt16",
            "u32" => "UInt32",
            "u64" => "UInt64",
            "f32" => "Float",
            "f64" => "Double",
            name => name,
        }
        .to_string(),
    }
}

fn render_factory(
    type_name: &str,
    factory: &Factory,
) -> String {
    let method = AsLowerCamelCase(&factory.name);
    let function = factory.function_name(type_name);
    let parameters = factory
        .arguments
        .iter()
        .map(|argument| format!("{}: {}", AsLowerCamelCase(&argument.name), swift_type(&argument.foreign_type)))
        .collect::<Vec<_>>()
        .join(", ");
    let arguments = factory
        .arguments
        .iter()
        .map(|argument| format!("{0}: {0}", AsLowerCamelCase(&argument.name)))
        .collect::<Vec<_>>()
        .join(", ");
    let (effects, call) = match (factory.is_async, factory.throws) {
        (false, false) => ("", ""),
        (true, false) => ("async ", "await "),
        (false, true) => ("throws ", "try "),
        (true, true) => ("async throws ", "try await "),
    };
    format!(
        r#"    public static func {method}({parameters}) {effects}-> {type_name} {{
        {call}{function}({arguments})
    }}
"#
    )
}

fn render_callback_factory(
    type_name: &str,
    factory: &CallbackFactory,
) -> String {
    let method = AsLowerCamelCase(&factory.name);
    let argument_types = factory.callback_arguments.iter().map(swift_type).collect::<Vec<_>>();
    let parameters = argument_types
        .iter()
        .enumerate()
        .map(|(index, argument_type)| format!("arg{index}: {argument_type}"))
        .collect::<Vec<_>>()
        .join(", ");
    let arguments = (0..argument_types.len()).map(|index| format!("arg{index}")).collect::<Vec<_>>().join(", ");
    let argument_types = argument_types.join(", ");
    format!(
        r#"    public typealias Closure = @Sendable ({argument_types}) -> Void

    private final class {type_name}HandlerClosureWrapper: Sendable, {type_name}Handler {{
        private let closure: Closure

        init(closure: @escaping Closure) {{
            self.closure = closure
        }}

        func onEvent({parameters}) {{
            closure({arguments})
        }}
    }}

    public static func {method}(closure: @escaping Closure) -> {type_name} {{
        {type_name}.{method}(handler: {type_name}HandlerClosureWrapper(closure: closure))
    }}
"#
    )
}

fn render_stream(stream: &Stream) -> String {
    let next_method = AsLowerCamelCase(&stream.next_method);
    let item_type = swift_type(&stream.item_type);
    let (capture, cancel) = match &stream.cancel_getter {
        Some(getter) => ("[weak self] ", format!("\n                self?.{}().cancel()", AsLowerCamelCase(getter))),
        None => ("", String::new()),
    };
    format!(
        r#"    public func iterator() -> AsyncThrowingStream<{item_type}, Swift.Error> {{
        AsyncThrowingStream<{item_type}, Swift.Error> {{ continuation in
            let task = Task {{
                while !Task.isCancelled {{
                    let item = await self.{next_method}()
                    guard let item else {{
                        continuation.finish()
                        break
                    }}
                    continuation.yield(item)
                }}
            }}
            continuation.onTermination = {{ {capture}_ in
                task.cancel(){cancel}
            }}
        }}
    }}
"#
    )
}
