use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};

use anyhow::{Context, Result};
use heck::AsLowerCamelCase;
use walkdir::WalkDir;

use crate::languages::foreign_extensions::{
    CallbackFactory, Factory, StreamBridge, collect_all, free_function_name, spell_rust_type,
};

pub fn generate_kotlin_extensions(
    crates_path: &Path,
    generated_sources_path: &Path,
    main_crate: &str,
) -> Result<()> {
    let mut main_source_path = None;
    let mut packages = BTreeSet::new();
    for entry in WalkDir::new(generated_sources_path) {
        let path = entry?.into_path();
        if path.extension().and_then(|extension| extension.to_str()) != Some("kt") {
            continue;
        }
        let source = fs::read_to_string(&path)?;
        let package = source
            .lines()
            .find_map(|line| line.strip_prefix("package "))
            .with_context(|| format!("{} declares no package", path.display()))?
            .trim()
            .to_string();
        if path.file_stem().and_then(|stem| stem.to_str()) == Some(main_crate) {
            main_source_path = Some((path, package.clone()));
        }
        packages.insert(package);
    }
    let (main_source_path, main_package) =
        main_source_path.with_context(|| format!("No {main_crate}.kt in {}", generated_sources_path.display()))?;
    packages.remove(&main_package);

    let (aliases, factories, callback_factories, stream_bridges) = collect_all(crates_path, rust_type_to_kotlin)?;
    let kotlin_source =
        render_extensions_file(&main_package, &packages, &aliases, &factories, &callback_factories, &stream_bridges);
    let directory = main_source_path.parent().context("Generated bindings have no directory")?;
    fs::write(directory.join("Extensions.kt"), kotlin_source)?;
    Ok(())
}

fn rust_type_to_kotlin(
    ty: &syn::Type,
    self_type_name: &str,
) -> Option<String> {
    spell_rust_type(
        ty,
        self_type_name,
        |name| {
            Some(match name {
                "String" => "String",
                "bool" => "Boolean",
                "i8" => "Byte",
                "i16" => "Short",
                "i32" => "Int",
                "i64" => "Long",
                "u8" => "UByte",
                "u16" => "UShort",
                "u32" => "UInt",
                "u64" => "ULong",
                "f32" => "Float",
                "f64" => "Double",
                _ => return None,
            })
        },
        |inner| format!("List<{}>", inner),
    )
}

fn render_extensions_file(
    package: &str,
    imported_packages: &BTreeSet<String>,
    aliases: &BTreeMap<String, String>,
    factories: &[Factory],
    callback_factories: &[CallbackFactory],
    stream_bridges: &[StreamBridge],
) -> String {
    let mut output = format!("// Auto-generated by cli-tools — do not edit.\n\npackage {package}\n\n");
    for imported_package in imported_packages {
        output.push_str(&format!("import {imported_package}.*\n"));
    }
    output.push_str("import kotlinx.coroutines.flow.Flow\n");
    output.push_str("import kotlinx.coroutines.flow.flow\n");
    output.push_str("import kotlinx.coroutines.flow.onCompletion\n\n");
    for (name, kotlin_type) in aliases {
        output.push_str(&format!("typealias {name} = {kotlin_type}\n\n"));
    }
    for factory in factories {
        output.push_str(&render_factory(factory));
    }
    for callback_factory in callback_factories {
        output.push_str(&render_callback_factory(callback_factory));
    }
    for stream_bridge in stream_bridges {
        output.push_str(&render_stream_bridge(stream_bridge));
    }
    format!("{}\n", output.trim_end())
}

fn render_factory(factory: &Factory) -> String {
    let type_name = &factory.type_name;
    let kotlin_method = AsLowerCamelCase(&factory.method_name);
    let free_function = free_function_name(factory);
    let args_signature = factory
        .arguments
        .iter()
        .map(|arg| format!("{}: {}", AsLowerCamelCase(&arg.name), arg.foreign_type))
        .collect::<Vec<_>>()
        .join(", ");
    let args_forward =
        factory.arguments.iter().map(|arg| AsLowerCamelCase(&arg.name).to_string()).collect::<Vec<_>>().join(", ");
    let modifier = if factory.is_async {
        "suspend "
    } else {
        ""
    };
    let optional = if factory.optional {
        "?"
    } else {
        ""
    };
    format!(
        "{modifier}fun {type_name}.Companion.{kotlin_method}({args_signature}): {type_name}{optional} = {free_function}({args_forward})\n\n",
    )
}

fn render_callback_factory(factory: &CallbackFactory) -> String {
    let type_name = &factory.type_name;
    let kotlin_method = AsLowerCamelCase(&factory.method_name);
    let closure_args_signature = factory
        .callback_arg_types
        .iter()
        .enumerate()
        .map(|(index, ty)| format!("arg{index}: {ty}"))
        .collect::<Vec<_>>()
        .join(", ");
    let closure_args_forward =
        (0..factory.callback_arg_types.len()).map(|index| format!("arg{index}")).collect::<Vec<_>>().join(", ");
    let closure_type_signature = format!("({}) -> Unit", factory.callback_arg_types.join(", "));
    format!(
        "fun {type_name}.Companion.{kotlin_method}(closure: {closure_type_signature}): {type_name} =\n    \
         {type_name}.{kotlin_method}(object : {type_name}Handler {{\n        \
         override fun onEvent({closure_args_signature}) = closure({closure_args_forward})\n    }})\n\n",
    )
}

fn render_stream_bridge(bridge: &StreamBridge) -> String {
    let type_name = &bridge.type_name;
    let item_type = &bridge.item_foreign_type;
    let kotlin_next = AsLowerCamelCase(&bridge.next_method_name);
    let cancel_hook = match &bridge.cancel_getter_name {
        Some(getter) => format!(".onCompletion {{ {}().cancel() }}", AsLowerCamelCase(getter)),
        None => String::new(),
    };
    format!(
        "fun {type_name}.asFlow(): Flow<{item_type}> =\n    flow {{\n        while (true) {{\n            \
         emit({kotlin_next}() ?: break)\n        }}\n    }}{cancel_hook}\n\n",
    )
}
